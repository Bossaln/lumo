/// Winzige 3×5-Schrift für Schilder und Aufkleber im Büro (Großbuchstaben, Ziffern, Ø).
public enum PixelFont {
    public static let width = 3
    public static let height = 5

    public static func glyph(_ ch: Character) -> [String]? {
        glyphs[Character(String(ch).uppercased())]
    }

    /// Breite eines Textes in Pixeln (mit je einem Pixel Abstand).
    public static func measure(_ string: String) -> Int {
        max(0, string.count * (width + 1) - 1)
    }

